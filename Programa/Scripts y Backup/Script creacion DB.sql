-- Cantidad de filas por tabla (esperado: Cliente=10, Cliente_Telefono=12, Prenda=13, Venta=25, Detalle_Venta=36, Factura=19)
SELECT 'Cliente' AS TABLA, COUNT(*) AS FILAS FROM Cliente
UNION ALL SELECT 'Cliente_Telefono', COUNT(*) FROM Cliente_Telefono
UNION ALL SELECT 'Prenda', COUNT(*) FROM Prenda
UNION ALL SELECT 'Venta', COUNT(*) FROM Venta
UNION ALL SELECT 'Detalle_Venta', COUNT(*) FROM Detalle_Venta
UNION ALL SELECT 'Factura', COUNT(*) FROM Factura;

-- Control: facturas cuyo importe no coincide con el total de la venta (debe devolver 0 filas)
SELECT v.NUM_VENTA, f.NUM_FACT_LEGAL, f.IMPORTE_FACTURA, t.TOTAL_VENTA
FROM Venta v
JOIN Factura f ON f.NUM_FACT_LEGAL = v.NUM_FACT_LEGAL
JOIN vw_total_venta t ON t.NUM_VENTA = v.NUM_VENTA
WHERE f.IMPORTE_FACTURA <> t.TOTAL_VENTA;


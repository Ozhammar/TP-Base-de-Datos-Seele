-- TABLAS
CREATE TABLE TipoDocumento (
 ID_TIPO_DOC INT NOT NULL,
 DESCRIPCION VARCHAR(11) NOT NULL,
 CONSTRAINT PK_TipoDocumento PRIMARY KEY (ID_TIPO_DOC)
);

CREATE TABLE TipoVenta (
 ID_TIPO_VTA INT NOT NULL,
 DESCRIPCION VARCHAR(10) NOT NULL,
 CONSTRAINT PK_TipoVenta PRIMARY KEY (ID_TIPO_VTA)
);

CREATE TABLE MedioPago (
 ID_MEDIO_PAGO INT NOT NULL,
 DESCRIPCION VARCHAR(20) NOT NULL,
 CONSTRAINT PK_MedioPago PRIMARY KEY (ID_MEDIO_PAGO)
);

CREATE TABLE EstadoVenta (
 ID_ESTADO_VTA INT NOT NULL,
 DESCRIPCION VARCHAR(20) NOT NULL,
 CONSTRAINT PK_EstadoVenta PRIMARY KEY (ID_ESTADO_VTA)
);

CREATE TABLE EstadoFactura (
 ID_ESTADO_FC INT NOT NULL,
 DESCRIPCION VARCHAR(20) NOT NULL,
 CONSTRAINT PK_EstadoFactura PRIMARY KEY (ID_ESTADO_FC)
);

CREATE TABLE Categoria (
 ID_CATEGORIA INT NOT NULL,
 DESCRIPCION VARCHAR(50) NOT NULL,
 CONSTRAINT PK_Categoria PRIMARY KEY (ID_CATEGORIA)
);

CREATE TABLE Color (
 ID_COLOR INT NOT NULL,
 DESCRIPCION VARCHAR(50) NOT NULL,
 CONSTRAINT PK_Color PRIMARY KEY (ID_COLOR)
);

CREATE TABLE Talle (
 ID_TALLE INT NOT NULL,
 DESCRIPCION VARCHAR(3) NOT NULL,
 CONSTRAINT PK_Talle PRIMARY KEY (ID_TALLE)
);

CREATE TABLE Cliente (
 NRO_DOC_CLIENTE VARCHAR(11) NOT NULL,
 ID_TIPO_DOC INT NOT NULL,
 APELLIDO_CLIENTE VARCHAR(30) NOT NULL,
 NOM_CLIENTE VARCHAR(30) NOT NULL,
 EMAIL_CLIENTE VARCHAR(50) NOT NULL,
 DOM_FACT_CLIENTE VARCHAR(100) NOT NULL,
 CONSTRAINT PK_Cliente PRIMARY KEY (NRO_DOC_CLIENTE),
 CONSTRAINT FK_Cliente_TipoDocumento FOREIGN KEY (ID_TIPO_DOC)
 REFERENCES TipoDocumento (ID_TIPO_DOC)
);

CREATE TABLE Telefono (
 TELEFONO VARCHAR(14) NOT NULL,
 CONSTRAINT PK_Telefono PRIMARY KEY (TELEFONO)
);

CREATE TABLE Cliente_Telefono (
 NRO_DOC_CLIENTE VARCHAR(11) NOT NULL,
 TELEFONO VARCHAR(14) NOT NULL,
 CONSTRAINT PK_Cliente_Telefono PRIMARY KEY (NRO_DOC_CLIENTE, TELEFONO),
 CONSTRAINT FK_Cliente_Telefono_Cliente FOREIGN KEY (NRO_DOC_CLIENTE)
 REFERENCES Cliente (NRO_DOC_CLIENTE),
 CONSTRAINT FK_Cliente_Telefono_Telefono FOREIGN KEY (TELEFONO)
 REFERENCES Telefono (TELEFONO)
);

CREATE TABLE Prenda (
 COD_PRENDA VARCHAR(16) NOT NULL,
 DESC_PRENDA VARCHAR(100) NOT NULL,
 ID_CATEGORIA INT NOT NULL,
 ID_COLOR INT NOT NULL,
 ID_TALLE INT NOT NULL,
 PRECIO_CATALOGO DECIMAL(10,2) NOT NULL,
 STOCK_DISP INT NOT NULL,
 CONSTRAINT PK_Prenda PRIMARY KEY (COD_PRENDA),
 CONSTRAINT FK_Prenda_Categoria FOREIGN KEY (ID_CATEGORIA) REFERENCES Categoria (ID_CATEGORIA),
 CONSTRAINT FK_Prenda_Color FOREIGN KEY (ID_COLOR) REFERENCES Color (ID_COLOR),
 CONSTRAINT FK_Prenda_Talle FOREIGN KEY (ID_TALLE) REFERENCES Talle (ID_TALLE),
 CONSTRAINT CK_Prenda_Precio CHECK (PRECIO_CATALOGO >= 0),
 CONSTRAINT CK_Prenda_Stock CHECK (STOCK_DISP >= 0)
);

CREATE TABLE Factura (
 NUM_FACT_LEGAL VARCHAR(15) NOT NULL,
 FECHA_FACTURA DATE NOT NULL,
 IMPORTE_FACTURA DECIMAL(10,2) NOT NULL,
 ID_ESTADO_FC INT NOT NULL,
 CONSTRAINT PK_Factura PRIMARY KEY (NUM_FACT_LEGAL),
 CONSTRAINT FK_Factura_EstadoFactura FOREIGN KEY (ID_ESTADO_FC)
 REFERENCES EstadoFactura (ID_ESTADO_FC),
 CONSTRAINT CK_Factura_Importe CHECK (IMPORTE_FACTURA >= 0)
);

CREATE TABLE Venta (
 NUM_VENTA INT NOT NULL AUTO_INCREMENT,
 NRO_DOC_CLIENTE VARCHAR(11) NOT NULL,
 ID_TIPO_VTA INT NOT NULL,
 ID_MEDIO_PAGO INT NOT NULL,
 ID_ESTADO_VTA INT NOT NULL,
 FECHA_VENTA DATE NOT NULL,
 NUM_FACT_LEGAL VARCHAR(15) NULL, -- opcional (relación 1 a 0..1)
 CONSTRAINT PK_Venta PRIMARY KEY (NUM_VENTA),
 /* En MySQL un UNIQUE admite varios NULL: permite muchas ventas sin factura
 e impide que dos ventas compartan una misma factura. */
 CONSTRAINT UQ_Venta_Factura UNIQUE (NUM_FACT_LEGAL),
 CONSTRAINT FK_Venta_Cliente FOREIGN KEY (NRO_DOC_CLIENTE) REFERENCES Cliente (NRO_DOC_CLIENTE),
 CONSTRAINT FK_Venta_TipoVenta FOREIGN KEY (ID_TIPO_VTA) REFERENCES TipoVenta (ID_TIPO_VTA),
 CONSTRAINT FK_Venta_MedioPago FOREIGN KEY (ID_MEDIO_PAGO) REFERENCES MedioPago (ID_MEDIO_PAGO),
 CONSTRAINT FK_Venta_EstadoVenta FOREIGN KEY (ID_ESTADO_VTA) REFERENCES EstadoVenta (ID_ESTADO_VTA),
 CONSTRAINT FK_Venta_Factura FOREIGN KEY (NUM_FACT_LEGAL) REFERENCES Factura (NUM_FACT_LEGAL)
);

CREATE TABLE Detalle_Venta (
 NUM_VENTA INT NOT NULL,
 COD_PRENDA VARCHAR(16) NOT NULL,
 CANT_PRENDA INT NOT NULL,
 VAL_UNIT DECIMAL(10,2) NOT NULL, -- precio cobrado en esa venta (histórico)
 CONSTRAINT PK_Detalle_Venta PRIMARY KEY (NUM_VENTA, COD_PRENDA),
 CONSTRAINT FK_Detalle_Venta_Venta FOREIGN KEY (NUM_VENTA) REFERENCES Venta (NUM_VENTA),
 CONSTRAINT FK_Detalle_Venta_Prenda FOREIGN KEY (COD_PRENDA) REFERENCES Prenda (COD_PRENDA),
 CONSTRAINT CK_Detalle_Cantidad CHECK (CANT_PRENDA > 0),
 CONSTRAINT CK_Detalle_ValUnit CHECK (VAL_UNIT >= 0)
);

-- VISTAS
CREATE VIEW vw_total_venta AS
SELECT d.NUM_VENTA,
 SUM(d.CANT_PRENDA) AS UNIDADES,
 SUM(d.CANT_PRENDA * d.VAL_UNIT) AS TOTAL_VENTA
FROM Detalle_Venta d
GROUP BY d.NUM_VENTA;

CREATE VIEW vw_ventas_por_periodo AS
SELECT YEAR(v.FECHA_VENTA) AS ANIO,
 MONTH(v.FECHA_VENTA) AS MES,
 tv.DESCRIPCION AS TIPO_VENTA,
 mp.DESCRIPCION AS MEDIO_PAGO,
 COUNT(*) AS CANT_VENTAS,
 SUM(t.TOTAL_VENTA) AS MONTO_TOTAL
FROM Venta v
JOIN vw_total_venta t ON t.NUM_VENTA = v.NUM_VENTA
JOIN TipoVenta tv ON tv.ID_TIPO_VTA = v.ID_TIPO_VTA
JOIN MedioPago mp ON mp.ID_MEDIO_PAGO = v.ID_MEDIO_PAGO
JOIN EstadoVenta ev ON ev.ID_ESTADO_VTA = v.ID_ESTADO_VTA
WHERE ev.DESCRIPCION <> 'Cancelada'
GROUP BY YEAR(v.FECHA_VENTA), MONTH(v.FECHA_VENTA), tv.DESCRIPCION, mp.DESCRIPCION;


CREATE VIEW vw_prendas_mas_vendidas AS
SELECT p.COD_PRENDA,
 p.DESC_PRENDA,
 c.DESCRIPCION AS CATEGORIA,
 co.DESCRIPCION AS COLOR,
 ta.DESCRIPCION AS TALLE,
 SUM(d.CANT_PRENDA) AS UNIDADES_VENDIDAS,
 SUM(d.CANT_PRENDA * d.VAL_UNIT) AS MONTO_VENDIDO
FROM Detalle_Venta d
JOIN Venta v ON v.NUM_VENTA = d.NUM_VENTA
JOIN EstadoVenta ev ON ev.ID_ESTADO_VTA = v.ID_ESTADO_VTA
JOIN Prenda p ON p.COD_PRENDA = d.COD_PRENDA
JOIN Categoria c ON c.ID_CATEGORIA = p.ID_CATEGORIA
JOIN Color co ON co.ID_COLOR = p.ID_COLOR
JOIN Talle ta ON ta.ID_TALLE = p.ID_TALLE
WHERE ev.DESCRIPCION <> 'Cancelada'
GROUP BY p.COD_PRENDA, p.DESC_PRENDA, c.DESCRIPCION, co.DESCRIPCION, ta.DESCRIPCION;

CREATE VIEW vw_ranking_clientes AS
SELECT RANK() OVER (ORDER BY SUM(t.TOTAL_VENTA) DESC) AS POSICION,
 cl.NRO_DOC_CLIENTE,
 cl.APELLIDO_CLIENTE,
 cl.NOM_CLIENTE,
 COUNT(*) AS CANT_VENTAS,
 SUM(t.TOTAL_VENTA) AS MONTO_COMPRADO
FROM Venta v
JOIN vw_total_venta t ON t.NUM_VENTA = v.NUM_VENTA
JOIN Cliente cl ON cl.NRO_DOC_CLIENTE = v.NRO_DOC_CLIENTE
JOIN EstadoVenta ev ON ev.ID_ESTADO_VTA = v.ID_ESTADO_VTA
WHERE ev.DESCRIPCION <> 'Cancelada'
GROUP BY cl.NRO_DOC_CLIENTE, cl.APELLIDO_CLIENTE, cl.NOM_CLIENTE;

CREATE VIEW vw_facturacion_por_periodo AS
SELECT YEAR(f.FECHA_FACTURA) AS `AÑO`,
 MONTH(f.FECHA_FACTURA) AS MES,
 ef.DESCRIPCION AS ESTADO_FACTURA,
 COUNT(*) AS CANT_FACTURAS,
 SUM(f.IMPORTE_FACTURA) AS IMPORTE_TOTAL
FROM Factura f
JOIN EstadoFactura ef ON ef.ID_ESTADO_FC = f.ID_ESTADO_FC
GROUP BY YEAR(f.FECHA_FACTURA), MONTH(f.FECHA_FACTURA), ef.DESCRIPCION;

CREATE VIEW vw_stock_disponible AS
SELECT p.COD_PRENDA,
 p.DESC_PRENDA,
 c.DESCRIPCION AS CATEGORIA,
 co.DESCRIPCION AS COLOR,
 ta.DESCRIPCION AS TALLE,
 p.PRECIO_CATALOGO,
 p.STOCK_DISP
FROM Prenda p
JOIN Categoria c ON c.ID_CATEGORIA = p.ID_CATEGORIA
JOIN Color co ON co.ID_COLOR = p.ID_COLOR
JOIN Talle ta ON ta.ID_TALLE = p.ID_TALLE;

